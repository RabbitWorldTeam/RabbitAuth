import { Peer, delay, rcon, queryPosition } from './client.mjs';
import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import mcData from 'minecraft-data';

const state = JSON.parse(await fs.readFile(new URL('./results-state.json', import.meta.url), 'utf8'));
const checks = [], peers = [];
const check = (value, label) => { if (!value) throw new Error('FAILED: ' + label); checks.push(label); console.log('PASS ' + label); };
const connect = async name => { const peer = new Peer(name); peers.push(peer); await peer.ready(); return peer; };
for (let i = 0; i < 100; i++) { try { await rcon('list'); break; } catch (error) { if (i === 99) throw error; await delay(500); } }
await delay(300);
try {
  const player = await connect(state.name);
  check(player.messages.some(m => m.includes('请登录')), 'restart revokes process-local auto-login tickets');
  check(player.packets.some(p => p.name === 'entity_effect' && p.data.duration === -1), 'configured pre-login blindness is sent');
  const watcher = await connect('AuthWatch');
  await watcher.command('register ' + state.watchPassword + ' ' + state.watchPassword, '注册数量');
  check(true, 'IP registration limit enforced against real database account');
  const third = new Peer('AuthThird'); peers.push(third);
  await third.wait(() => third.ended, 'IP limit rejection');
  check(third.reason.includes('同时连接'), 'IP connection limit includes unauthenticated sessions');
  const allowed = 'AUTH_ALLOW_' + crypto.randomBytes(4).toString('hex');
  await player.command('say ' + allowed);
  await watcher.wait(() => watcher.messages.some(m => m.includes(allowed)), 'allowed command broadcast');
  check(true, 'regex-whitelisted command executes before login');
  const chat = 'AUTH_CHAT_' + crypto.randomBytes(4).toString('hex');
  player.client.chat(chat); await delay(400);
  check((await fs.readFile(new URL('../../run/server/logs/latest.log', import.meta.url), 'utf8')).includes(chat), 'before-login-allow-chat permits actual chat');
  const position = await queryPosition(state.name);
  await rcon('summon minecraft:pig ' + (position[0] + 1) + ' ' + position[1] + ' ' + position[2] + ' {Tags:["RabbitAuthTarget"],NoAI:1b,Silent:1b}');
  const pigType = mcData('1.21.1').entitiesByName.pig.id;
  await player.wait(() => player.packets.some(p => p.name === 'spawn_entity' && p.data.type === pigType), 'test target spawn');
  const target = player.packets.findLast(p => p.name === 'spawn_entity' && p.data.type === pigType).data.entityId;
  const health = await rcon('data get entity @e[tag=RabbitAuthTarget,limit=1] Health');
  player.client.write('use_entity', { target, mouse: 1, sneaking: false });
  await delay(200);
  check((await rcon('data get entity @e[tag=RabbitAuthTarget,limit=1] Health')) === health, 'attack packet cannot damage nearby mob before login');
  await rcon('kill @e[tag=RabbitAuthTarget]');
  await rcon('item replace entity ' + state.name + ' hotbar.0 with minecraft:stone 8');
  await rcon('setblock 1 -60 0 minecraft:air');
  player.client.write('block_place', { hand: 0, location: { x: 1, y: -61, z: 0 }, direction: 1, cursorX: .5, cursorY: 1, cursorZ: .5, insideBlock: false, sequence: 3 });
  await delay(150);
  check((await rcon('execute if block 1 -60 0 minecraft:air')).includes('Test passed'), 'block placement packet blocked before login');
  await player.command('login ' + state.password, '认证成功');
  check(player.packets.some(p => p.name === 'remove_entity_effect'), 'pre-login blindness removed after login');
  await watcher.close();
  await player.close();
  const tooSoon = new Peer(state.name); peers.push(tooSoon);
  await tooSoon.wait(() => tooSoon.ended, 'reentry cooldown');
  check(tooSoon.reason.includes('上次下线'), 'configured tick reentry cooldown rejects immediate reconnect');
  await delay(1100);
  const automatic = await connect(state.name);
  await automatic.wait(() => automatic.messages.some(m => m.includes('认证成功')), 'same-IP automatic authentication');
  check(true, 'same-IP authenticated logout grants password-free reentry');
  await automatic.close();
  const ticketTime = Date.now();
  const timeout = await connect('AuthTimeout');
  await timeout.wait(() => timeout.ended, 'authentication timeout', 15000);
  check(timeout.reason.includes('登录超时'), 'configured login timeout disconnects unauthenticated client');
  console.log('Waiting for configured one-minute auto-login ticket expiry');
  await delay(Math.max(0, 63000 - (Date.now() - ticketTime)));
  const expired = await connect(state.name);
  check(expired.messages.some(m => m.includes('请登录')) && !expired.messages.some(m => m.includes('认证成功')), 'expired same-IP ticket requires password');
  await expired.command('login ' + state.password, '认证成功');
  await rcon('item replace entity ' + state.name + ' hotbar.0 with minecraft:diamond 7');
  await expired.close();
  await fs.writeFile(new URL('./results-options.json', import.meta.url), JSON.stringify({ passed: true, checks }, null, 2));
  console.log('PROTOCOL_TEST_OK options: ' + checks.length + ' checks');
  await rcon('stop');
} catch (error) {
  console.error(error.stack);
  await fs.writeFile(new URL('./results-options.json', import.meta.url), JSON.stringify({ passed: false, checks, error: error.message }, null, 2));
  process.exitCode = 1;
} finally { for (const peer of peers) if (!peer.ended) peer.client.end(); }
